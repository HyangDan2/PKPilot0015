export const DICT: Record<Lang, Record<TKey, string>> = { ko: KO, en: EN };

export type Vars = Record<string, string | number>;

/** `{name}`-style interpolation; unknown placeholders are left untouched. */
export function translate(lang: Lang, key: TKey, vars?: Vars): string {
  const template = DICT[lang][key] ?? DICT.ko[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole);
}

export interface I18n {
  lang: Lang;
  t: (key: TKey, vars?: Vars) => string;
  setLang: (lang: Lang) => void;
}

export const I18nContext = createContext<I18n | null>(null);

export function useI18n(): I18n {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nContext.Provider');
  return value;
}
